"""
Data Contracts and Schema Definitions for Automated Execution & Trading Bot.
Strict Pydantic v2 models adhering to Zero LLM Arithmetic and Type Safety.
"""

from datetime import UTC, datetime
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field


class BotMode(str, Enum):
    PAPER_TRADING = "PAPER_TRADING"
    LIVE_BINANCE = "LIVE_BINANCE"


class BotStatus(str, Enum):
    STOPPED = "STOPPED"
    RUNNING = "RUNNING"
    PAUSED = "PAUSED"


class StrategyType(str, Enum):
    LIQUIDATION_SWEEP_REVERSAL = "LIQUIDATION_SWEEP_REVERSAL"
    SPOT_DCA_GRID = "SPOT_DCA_GRID"
    ORDERBOOK_IMBALANCE_FLOW = "ORDERBOOK_IMBALANCE_FLOW"


class SignalDirection(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"


class TradeSignal(BaseModel):
    """Deterministic trading signal generated by Strategy Engine."""

    model_config = ConfigDict(strict=True, frozen=True)

    symbol: str
    direction: SignalDirection
    strategy: StrategyType
    entry_price: float = Field(..., gt=0.0)
    stop_loss_price: float = Field(..., gt=0.0)
    take_profit_price: float = Field(..., gt=0.0)
    risk_reward_ratio: float = Field(..., ge=1.0)
    rationale: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class OrderRequest(BaseModel):
    """Structured order request dispatched to execution engine."""

    model_config = ConfigDict(strict=True, frozen=True)

    order_id: str
    symbol: str
    direction: SignalDirection
    quantity: float = Field(..., gt=0.0)
    price: float = Field(..., gt=0.0)
    stop_loss: float = Field(..., gt=0.0)
    take_profit: float = Field(..., gt=0.0)
    risk_usd: float = Field(..., ge=0.0)
    strategy: StrategyType
    mode: BotMode
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class TradeRecord(BaseModel):
    """Historical or active trade record for telemetry and accounting."""

    model_config = ConfigDict(strict=True)

    trade_id: str
    symbol: str
    direction: SignalDirection
    strategy: StrategyType
    entry_price: float
    exit_price: float | None = None
    quantity: float
    stop_loss: float
    take_profit: float
    realized_pnl_usd: float = 0.0
    fee_usd: float = 0.0
    is_winner: bool | None = None
    entry_time: datetime
    exit_time: datetime | None = None
    exit_reason: str = ""  # "TAKE_PROFIT", "STOP_LOSS", "MANUAL", "RISK_VETO"
    mode: BotMode


class BotPerformanceStats(BaseModel):
    """Quantitative performance and statistical metrics."""

    model_config = ConfigDict(strict=True, frozen=True)

    total_trades: int
    winning_trades: int
    losing_trades: int
    win_rate_pct: float
    profit_factor: float
    expected_value_r: float  # Mathematical EV per trade in R-multiples
    total_realized_pnl_usd: float
    current_balance_usd: float
    max_drawdown_pct: float
